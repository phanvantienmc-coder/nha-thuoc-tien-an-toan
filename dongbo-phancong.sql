-- Bổ sung phân công còn thiếu theo thuốc phụ trách, không xóa phân công có sẵn.
SET XACT_ABORT ON;
BEGIN TRAN;
INSERT dbo.PHANCONG(SOHD,MADUOCSI)
SELECT DISTINCT h.SOHD,d.MADUOCSI
FROM dbo.HOADON h WITH (TABLOCKX,HOLDLOCK)
JOIN dbo.CHITIETHOADON c ON c.SOHD=h.SOHD
JOIN dbo.DUOCSI_CHUYENTHUOC d ON d.MATHUOC=c.MATHUOC
WHERE (h.TRANGTHAI IS NULL OR h.TRANGTHAI<>'da_huy')
  AND NOT EXISTS(SELECT 1 FROM dbo.PHANCONG p
    WHERE p.SOHD=h.SOHD AND p.MADUOCSI=d.MADUOCSI);
COMMIT;
